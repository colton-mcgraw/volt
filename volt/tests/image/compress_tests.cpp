    void checksums()
    {
        // The check values of the CRC catalogue and of the Adler-32 paper's
        // usual example.
        CHECK(compress::crc32(from_text("123456789")) == 0xCBF43926u);
        CHECK(compress::crc32(from_text("")) == 0u);
        CHECK(compress::adler32(from_text("Wikipedia")) == 0x11E60398u);
        CHECK(compress::adler32(from_text("")) == 1u);

        const bytes data = reference_input();
        CHECK(compress::crc32(data) == 0x1bd9dac6u);
        CHECK(compress::adler32(data) == 0x9ba7c102u);

        // In pieces, continuing the running value.
        const std::span<const std::uint8_t> all(data);
        CHECK(compress::crc32(all.subspan(1000), compress::crc32(all.first(1000))) == 0x1bd9dac6u);
        CHECK(compress::adler32(all.subspan(1000), compress::adler32(all.first(1000))) == 0x9ba7c102u);

        // Long enough for Adler-32's deferred modulo to matter.
        const bytes ones(100000, 0xFF);
        std::uint32_t a = 1;
        std::uint32_t b = 0;
        for (const std::uint8_t byte : ones)
        {
            a = (a + byte) % 65521;
            b = (b + a) % 65521;
        }
        CHECK(compress::adler32(ones) == ((b << 16) | a));
    }

    void foreign_streams()
    {
        const bytes expected = reference_input();
        for (const std::span<const std::uint8_t> stream :
             {std::span<const std::uint8_t>(zlib_dynamic), std::span<const std::uint8_t>(zlib_fixed)})
        {
            auto result = compress::zlib_decompress(stream);
            if (!result)
                std::fprintf(stderr, "reference stream: %s\n", result.error().c_str());
            CHECK(result.has_value());
            if (result)
                CHECK(*result == expected);
        }
    }

    void round_trip(const bytes &data, const char *what)
    {
        for (int level = 0; level <= 9; ++level)
        {
            const bytes packed = compress::zlib_compress(data, level);
            auto unpacked = compress::zlib_decompress(packed);
            const bool ok = unpacked.has_value() && *unpacked == data;
            if (!ok)
                std::fprintf(stderr, "round trip of %s at level %d failed: %s\n", what, level,
                             unpacked ? "data differs" : unpacked.error().c_str());
            CHECK(ok);
        }

        const bytes gz = compress::gzip_compress(data);
        auto back = compress::gzip_decompress(gz);
        CHECK(back.has_value() && *back == data);

        auto raw = compress::inflate(compress::deflate(data, 6));
        CHECK(raw.has_value() && *raw == data);
    }

    void round_trips()
    {
        round_trip({}, "empty input");
        round_trip({42}, "one byte");
        round_trip(reference_input(), "the reference input");

        tests::xorshift random;
        bytes noise(200000);
        for (auto &byte : noise)
            byte = static_cast<std::uint8_t>(random.next());
        round_trip(noise, "incompressible input");

        // Incompressible data should be stored, not expanded.
        CHECK(compress::deflate(noise, 9).size() < noise.size() + noise.size() / 1000 + 16);

        const bytes zeros(1 << 20, 0);
        round_trip(zeros, "a megabyte of zeros");
        CHECK(compress::deflate(zeros, 6).size() < 2000);

        // Text-like: a small alphabet with repeats at many distances.
        bytes text;
        const char *words[] = {"resistor ", "capacitor ", "inductor ", "net ", "pin ", "via ", "trace ", "\n"};
        for (int i = 0; i < 40000; ++i)
            for (const char *c = words[random.next() % 8]; *c != 0; ++c)
                text.push_back(static_cast<std::uint8_t>(*c));
        round_trip(text, "text");
        CHECK(compress::deflate(text, 6).size() < text.size() / 3);

        // Runs at every length near the match limits.
        bytes runs;
        for (int length = 1; length < 600; ++length)
            for (int i = 0; i < length; ++i)
                runs.push_back(static_cast<std::uint8_t>(length));
        round_trip(runs, "runs");

        // Repeats exactly at and beyond the 32 KiB window.
        bytes far(100000);
        for (std::size_t i = 0; i < far.size(); ++i)
            far[i] = i < 32768 ? static_cast<std::uint8_t>(random.next()) : far[i - 32768];
        round_trip(far, "repeats a window back");
    }

    void malformed_streams()
    {
        CHECK(!compress::zlib_decompress({}).has_value());
        CHECK(!compress::inflate({}).has_value());

        // Block type 3 is reserved.
        const bytes reserved{0x07};
        CHECK(!compress::inflate(reserved).has_value());

        // A stored block whose length does not match its complement.
        const bytes stored{0x01, 0x05, 0x00, 0x00, 0x00, 'a', 'b', 'c', 'd', 'e'};
        CHECK(!compress::inflate(stored).has_value());

        // A distance reaching before the start: fixed block, literal 'a',
        // then length 3 at distance 2.
        const bytes before_start{0x4b, 0x04, 0x42, 0x00};
        CHECK(!compress::inflate(before_start).has_value());

        // The output limit holds.
        const bytes zeros(100000, 0);
        const bytes packed = compress::zlib_compress(zeros);
        compress::inflate_options small;
        small.max_output = 50000;
        CHECK(!compress::zlib_decompress(packed, small).has_value());

        // A wrong checksum is caught.
        bytes broken = packed;
        broken.back() ^= 1;
        CHECK(!compress::zlib_decompress(broken).has_value());

        // Truncation anywhere and random damage never crash; truncation is
        // always noticed.
        const bytes data = reference_input();
        const bytes good = compress::zlib_compress(data, 9);
        for (std::size_t length = 0; length < good.size(); ++length)
            CHECK(!compress::zlib_decompress(std::span<const std::uint8_t>(good).first(length)).has_value());

        tests::xorshift random;
        int decoded = 0;
        for (int trial = 0; trial < 3000; ++trial)
        {
            bytes damaged = good;
            const int flips = 1 + static_cast<int>(random.next() % 4);
            for (int f = 0; f < flips; ++f)
                damaged[random.next() % damaged.size()] ^= static_cast<std::uint8_t>(1u << (random.next() % 8));
            auto result = compress::zlib_decompress(damaged);
            decoded += result.has_value() && *result == data;
        }
        // Whatever got through intact had to be undamaged in effect.
        CHECK(decoded < 3000);

        for (int trial = 0; trial < 3000; ++trial)
        {
            bytes junk(1 + random.next() % 300);
            for (auto &byte : junk)
                byte = static_cast<std::uint8_t>(random.next());
            (void)compress::inflate(junk);
        }
    }
